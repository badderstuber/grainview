#!/usr/bin/env python3
"""gen_pico_map.py - write the Pico's generated data, so the Mac side stays the one
source of truth:
    pico/mg_map.py    addresses + decode rules for the Pico's own poll (pico/mgpoll.py),
                      from the hardware-tested mg_* helpers, the server, gv_settings.json
    pico/gv_fonts.py  the emulator's bitmap fonts (fonts/gv_fonts.js) used by the Pico UI
    pico/gv_cat.py    the settings catalogue (gv_settings.json) the Pico UI lists

    tools/venv/bin/python tools/gen_pico_map.py      # (gv_pico.py deploy runs it too)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import grainview_server as G  # noqa: E402

L, P, PR, R, S = G.L, G.P, G.PR, G.R, G.S
PICO = os.path.join(os.path.dirname(HERE), "pico")
OUT = os.path.join(PICO, "mg_map.py")
FONTS_JS = os.path.join(HERE, "fonts", "gv_fonts.js")
FONTS = ("spleen-5x8", "spleen-6x12", "spleen-8x16", "spleen-16x32")   # gv_draw.js FONT_SETS.Spleen


def settings():
    """(group, key, t, addr, off, fn, inv, n_options, min, max, step, dp, scale, recip) per
    RAM setting (mg_set.py: fn / inv = the change callback, None = not writable that way)."""
    rows = []
    for g, e in G.ram_entries():
        r = e["ram"]
        rows.append((g, e["key"], r["t"],
                     int(r["addr"], 16) if "addr" in r else None,
                     int(r["off"], 16) if "off" in r else None,
                     r.get("fn"), int(r["inv"], 16) if r.get("inv") else None,
                     len(e.get("options", ())),
                     e.get("min"), e.get("max"), e.get("step"), e.get("dp", 3),
                     r.get("scale", 1), r.get("recip")))
    return rows


def main():
    h = lambda v: "0x%08X" % v  # noqa: E731
    lines = [
        "# GENERATED by tools/gen_pico_map.py from mg_load / mg_param / mg_preset / mg_rec /",
        "# grainview_server / gv_settings.json - don't edit, regenerate.",
        "SOUND_BASE, SOUND_STRIDE = %s, 0x%X" % (h(L.SOUND_BASE), L.SOUND_STRIDE),
        "BLOCK_LO, BLOCK_HI = 0x%X, 0x%X       # per-sound read: scene A .. end of scene B mods"
        % (G.SwdBackend.BLOCK_LO, G.SwdBackend.BLOCK_HI),
        "SCENE_B, MOD_VALS, MOD_STRIDE = 0x%X, 0x%X, 0x%X" % (P.SCENE_B, P.MOD_VALS, P.MOD_STRIDE),
        "PARAMS = %r" % (tuple((k, o) for k, (o, _, _) in P.PARAMS.items()),),
        "MOD_SRC = %r" % (tuple(P.MOD_SRC.items()),),
        "SRC_OFF, LINK_RS, LINK_SP = 0x%X, 0x%X, 0x%X" % (L.SRC_OFF, G.FLAG_LINK_RS, G.FLAG_LINK_SP),
        "FNAME_OFF = {%s}" % ", ".join("%d: 0x%X" % kv for kv in L.FNAME_OFF.items()),
        "FOLDER_NAMES = %r" % G.FOLDER_NAMES,
        "CURSORS = %s" % h(L.CURSORS),
        "CUR_SOUND, PLAYING, EDIT_SCENE = %s, %s, %s" % (h(L.CUR_SOUND), h(L.PLAYING), h(P.EDIT_SCENE)),
        "STATE = %s                 # engine/UI state block (mg_load.select_nohalt)" % h(L.STATE),
        "EVENTS, EV_PLAY_SELECTED = %s, %d   # engine event bits (mg_load.post_event_nohalt)"
        % (h(L.EVENTS), L.EV_PLAY_SELECTED),
        "SD_STATE, SIZE_MODE, SYNC, CLOCK_PERIOD = %s, %s, %s, %s"
        % (h(L.SD_STATE), h(G.G_SIZE_MODE), h(G.G_SYNC), h(G.G_CLOCK_PERIOD)),
        "LIVE = %s" % "(%s)" % ", ".join("(%r, %s)" % (k, h(P.LIVE[k])) for k in G.NAMES),
        "MORPH = %s" % h(P.LIVE["MORPH"]),
        "CUR_PROJECT, CUR_PRESET = %s, %s" % (h(PR.CUR_PROJECT), h(PR.CUR_PRESET)),
        "PROJECT_EXISTS, PRESET_EXISTS, PRESET_LOCKED = %s, %s, %s"
        % (h(PR.PROJECT_EXISTS), h(PR.PRESET_EXISTS), h(PR.PRESET_LOCKED)),
        "SLOTS = %d" % PR.SLOTS,
        "# the firmware all this is for (mg_load.FW_*): its flash image's SHA-256 (pico/mgfw.py)",
        "FW_VERSION, FW_BASE, FW_SIZE = %r, %s, %d" % (L.FW_VERSION, h(L.FW_BASE), L.FW_SIZE),
        "FW_SHA256 = %r" % L.FW_SHA256,
        "# FILE (pico/mgfile.py): file lists, loads, presets / projects - one-halt calls",
        "COUNTS, REC_LIST = %s, %s" % (h(L.COUNTS), h(L.REC_LIST)),
        "LISTS = {%s}" % ", ".join("%d: %s" % (k, h(v)) for k, v in L.LISTS.items()),
        "MAX_FILES = {%s}" % ", ".join("%d: 0x%X" % kv for kv in L.MAX_FILES.items()),
        "EMPTY_MASK, AUDIO_LEN, LOST_OFF = %s, %s, 0x%X" % (h(L.EMPTY_MASK), h(L.AUDIO_LEN), L.LOST_OFF),
        "IDLE_LO, IDLE_HI = %s, %s" % (h(L.IDLE_LO), h(L.IDLE_HI)),
        "BROWSE_LOAD_FN, SET_FOLDER_FN, BROWSER_UI = %s, %s, %s"
        % (h(L.BROWSE_LOAD_FN), h(L.SET_FOLDER_FN), h(L.BROWSER_UI)),
        "LOAD_PRESET_FN, SAVE_PRESET_FN, LOCK_PRESET_FN, LOAD_PROJECT_FN = %s, %s, %s, %s"
        % (h(PR.LOAD_PRESET_FN), h(PR.SAVE_PRESET_FN), h(PR.LOCK_PRESET_FN), h(PR.LOAD_PROJECT_FN)),
        "SD_PROJECT, PROJECT_DIRTY, AUTOSAVE_TICK = %s, %s, %s"
        % (h(PR.PROJECT), h(PR.PROJECT_DIRTY), h(PR.AUTOSAVE_TICK)),
        "# Live Sounds (pico/mgrec.py = mg_rec.set_live; docs/RECORDER.md)",
        "LIVE_REC, LIVE_VPTR, LIVE_MASK, REC_MODE = 0x%X, %s, %s, %s"
        % (R.LIVE_REC, h(R.LIVE_VPTR), h(R.LIVE_MASK), h(R.REC_MODE)),
        "LIVE_SET_FN, LIVE_DEFAULTS_FN = %s, %s" % (h(R.LIVE_SET_FN), h(R.LIVE_DEFAULTS_FN)),
        "# the recorder (pico/mgrec.py = mg_rec.rec_do / rec_snapshot; docs/RECORDER.md)",
        "REC_SIZE, REC_STATE, REC_FILL, REC_TAKE = %s, %s, %s, %s"
        % (h(R.REC_SIZE), h(R.REC_STATE), h(R.REC_FILL), h(R.REC_TAKE)),
        "TAKE_MIN, SLOTS_END = %d, %s" % (R.TAKE_MIN, h(R.SLOTS_END)),
        "SAVE_REQ, PAGE, HOME, HOME_BLINK, CLEAR = %s, %s, %s, %s, %s"
        % (h(R.SAVE_REQ), h(R.PAGE), h(R.HOME), h(R.HOME_BLINK), h(R.CLEAR)),
        "SAMPLE_CLICK_FN, SAMPLE_LONG_FN, SOUND_DOWN_FN = %s, %s, %s"
        % (h(R.SAMPLE_CLICK_FN), h(R.SAMPLE_LONG_FN), h(R.SOUND_DOWN_FN)),
        "CLEAR_FN, CLEAR_LEAVE_FN = %s, %s   # CLEAR_FN: button 0 ONLY (1 = load Init preset)"
        % (h(R.CLEAR_FN), h(R.CLEAR_LEAVE_FN)),
        "SETTINGS_EVERY_MS = %d" % (G.SETTINGS_EVERY * 1000),
        "# (group, key, type, addr, off, fn, inv, n_options, min, max, step, dp, scale, recip)",
        "VTABLES = (%s, %s)   # mg_set.VTABLES" % (h(S.VTABLES[0]), h(S.VTABLES[1])),
        "SETTINGS = (",
        *("    (%s)," % ", ".join(h(v) if i in (3, 4, 6) and v is not None else repr(v)
                                for i, v in enumerate(r)) for r in settings()),
        ")",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, os.path.dirname(HERE)))
    fonts()
    catalogue()


def catalogue():
    """pico/gv_cat.py: CAT[group] = [entry dicts], the fields the UI shows (no "ram"/"default")."""
    keep = ("key", "label", "type", "options", "fmt", "dp", "signed", "panel", "min", "max", "step")
    out = os.path.join(PICO, "gv_cat.py")
    with open(out, "w") as f:
        f.write("# GENERATED by tools/gen_pico_map.py from tools/gv_settings.json - don't edit.\n"
                "CAT = {\n")
        for g, entries in G.SETTINGS_CAT.items():
            f.write("    %r: [\n" % g)
            for e in entries:
                f.write("        %r,\n" % {k: e[k] for k in keep if k in e})
            f.write("    ],\n")
        f.write("}\n")
    print("wrote", os.path.relpath(out, os.path.dirname(HERE)))


def fonts():
    """pico/gv_fonts.py: FONTS[name] = (ascent, descent, cap, {code: (dw, w, h, xo, yo, rows)}),
    rows = the BDF bitmap, ceil(w / 8) bytes per row, MSB = left (framebuf MONO_HLSB)."""
    src = open(FONTS_JS).read()
    js = json.loads(src[src.index("{"):src.rindex("}") + 1])
    out = os.path.join(PICO, "gv_fonts.py")
    with open(out, "w") as f:
        f.write("# GENERATED by tools/gen_pico_map.py from tools/fonts/gv_fonts.js (u8g2 BDF\n"
                "# fonts; licences in tools/fonts/README.md) - don't edit, regenerate.\n"
                "FONTS = {\n")
        for name in FONTS:
            ft = js[name]
            f.write("    %r: (%d, %d, %d, {  # %s\n" % (name, ft["ascent"], ft["descent"], ft["cap"],
                                                     ft["copyright"][:60]))
            for code, (dw, w, h, xo, yo, hx) in sorted(ft["g"].items(), key=lambda kv: int(kv[0])):
                f.write("        %s: (%d, %d, %d, %d, %d, %r),\n"
                        % (code, dw, w, h, xo, yo, bytes.fromhex(hx)))
            f.write("    }),\n")
        f.write("}\n")
    print("wrote", os.path.relpath(out, os.path.dirname(HERE)))


if __name__ == "__main__":
    main()
